// Concatenate drizzle-kit v1 nested migrations into a TS string the Worker
// can import. Wrangler cannot readdir() migrations at runtime.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = join(repoRoot, 'migrations');
const outFile = join(repoRoot, 'src/db/baseline.ts');

const folders = readdirSync(migrationsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const sql = folders
  .map((folder) => join(migrationsDir, folder, 'migration.sql'))
  .filter((path) => existsSync(path))
  .map((path) => readFileSync(path, 'utf8'))
  .join('\n--> statement-breakpoint\n');

if (!sql.trim()) {
  throw new Error('no generated migration SQL found under migrations/');
}

writeFileSync(
  outFile,
  `// Generated by scripts/embed-baseline.mjs. Do not edit.\n` +
    `export const BASELINE_MIGRATION_SQL = ${JSON.stringify(sql)};\n`,
);

console.log(`wrote ${outFile} (${sql.length} chars, ${folders.length} migration(s))`);
